/* يُستدعى مرة واحدة عند أول فتح — ولا يدهس مكتبة موجودة أبدًا */
export function seedLibrary(lib) {
  if (lib && Object.keys(lib.items || {}).length > 0) return lib;
  return {
    items: Object.fromEntries(SEED_RESOURCES.map(r => [r.id, { ...r }])),
    seededAt: new Date().toISOString().slice(0, 10),
    markup: 0.25,
  };
}

export function seedRecipes(book) {
  if (book?.recipes && Object.keys(book.recipes).length > 0) return book;
  return { ...book, recipes: JSON.parse(JSON.stringify(SEED_RECIPES)) };
}
